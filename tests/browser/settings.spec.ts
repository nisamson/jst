import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

async function openSettings(page: Page) {
  await page.getByRole('banner').getByRole('button', { name: 'Settings', exact: true }).click()
  return page.getByRole('dialog', { name: 'Settings', exact: true })
}

test('header and theme settings work on mobile, persist, and follow system changes', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/privacy')
  const header = page.getByRole('banner')
  await expect(header.getByRole('link', { name: 'Job Search Tracker', exact: true })).toHaveAttribute('href', '/')
  await expect(header.locator('img')).toHaveAttribute('src', '/jst-logo.svg')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
  await page.setViewportSize({ width: 320, height: 812 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
  await expect(header.getByRole('button', { name: 'Settings', exact: true })).toBeInViewport()
  let settings = await openSettings(page)
  const theme = settings.getByRole('combobox', { name: 'Theme', exact: true })
  await expect(theme).toHaveValue('System')
  await expect(page.locator('html')).toHaveAttribute('data-mantine-color-scheme', 'dark')
  await theme.click()
  await page.getByRole('option', { name: 'Light', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-mantine-color-scheme', 'light')
  await settings.getByRole('button', { name: 'Close', exact: true }).click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-mantine-color-scheme', 'light')
  settings = await openSettings(page)
  await settings.getByRole('combobox', { name: 'Theme' }).click()
  await page.getByRole('option', { name: 'Dark', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-mantine-color-scheme', 'dark')
  await settings.getByRole('combobox', { name: 'Theme' }).click()
  await page.getByRole('option', { name: 'System', exact: true }).click()
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(page.locator('html')).toHaveAttribute('data-mantine-color-scheme', 'light')
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveAttribute('data-mantine-color-scheme', 'dark')
})

test('advanced display hides technical information and developer tools without losing records', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(navigator.storage, 'persisted', { configurable: true, value: async () => true })
    Object.defineProperty(navigator.storage, 'persist', { configurable: true, value: async () => true })
  })
  await page.goto('/')
  await expect(page.getByRole('status')).toHaveText('Local SQLite storage is ready.')
  await page.getByRole('button', { name: 'Create profile', exact: true }).click()
  await page.getByRole('textbox', { name: 'Profile label' }).fill('Settings profile')
  await page.locator('form').getByRole('button', { name: 'Create profile', exact: true }).click()
  await page.getByRole('button', { name: 'Continue without syncing' }).click()
  const tools = page.getByRole('region', { name: 'Developer claim tools' })
  await tools.getByRole('button', { name: 'Add dummy claims', exact: true }).click()
  await expect(page.getByText('Record created:', { exact: false })).toBeVisible()
  await expect(page.getByText('Technical details', { exact: true }).first()).toBeVisible()
  const selectedUrl = page.url()
  let settings = await openSettings(page)
  await expect(settings.getByRole('switch', { name: 'Advanced display' })).toBeChecked()
  await settings.getByRole('switch', { name: 'Advanced display' }).uncheck()
  await settings.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(tools).toHaveCount(0)
  await expect(page.getByText('Record created:', { exact: false })).toHaveCount(0)
  await expect(page.getByText('Technical details', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Local SQLite storage is ready.', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Local-only records can still be lost or cleared', { exact: false })).toBeVisible()
  await expect(page).toHaveURL(selectedUrl)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Claims overview' })).toBeVisible()
  await expect(tools).toHaveCount(0)
  settings = await openSettings(page)
  await expect(settings.getByRole('switch', { name: 'Advanced display' })).not.toBeChecked()
  await settings.getByRole('switch', { name: 'Advanced display' }).check()
  await settings.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(tools).toBeVisible()
  await expect(page.getByText('Record created:', { exact: false })).toBeVisible()
})

test('advanced off hides diagnostic entry points but preserves read-only and storage warnings', async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('jst-advanced-display', 'false')
    Object.defineProperty(navigator.storage, 'persisted', { configurable: true, value: async () => false })
    Object.defineProperty(navigator.storage, 'persist', { configurable: true, value: async () => false })
  })
  await page.goto('/')
  await expect(page.getByRole('link', { name: 'Storage diagnostics', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Create profile', exact: true }).click()
  await page.getByRole('textbox', { name: 'Profile label' }).fill('Read-only settings')
  await page.locator('form').getByRole('button', { name: 'Create profile', exact: true }).click()
  await page.getByRole('button', { name: 'Continue without syncing' }).click()
  await expect(page.getByRole('note', { name: 'Profile is read-only' })).toBeVisible()
  await expect(page.getByRole('note', { name: 'Persistent storage is not confirmed' })).toBeVisible()
  await page.goto('/diagnostics/storage')
  await expect(page.getByText('Enable Advanced display in Settings', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Write and reopen test record' })).toHaveCount(0)
  const settings = await openSettings(page)
  await settings.getByRole('switch', { name: 'Advanced display' }).check()
  await settings.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Write and reopen test record' })).toBeVisible()
  await page.addInitScript(() => {
    Object.defineProperty(navigator.storage, 'getDirectory', { configurable: true, value: undefined })
  })
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('Local storage is unavailable.')
  await expect(page.getByRole('alert')).toContainText('origin-private file system')
  await expect(page.getByRole('button', { name: 'Retry storage setup' })).toBeVisible()
})

test('advanced display remains usable for the visit when preference storage is blocked', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(window, 'localStorage', {
      configurable: true,
      get() { throw new DOMException('Storage blocked', 'SecurityError') },
    })
  })
  await page.goto('/privacy')
  await page.getByRole('button', { name: 'I understand', exact: true }).click()
  let settings = await openSettings(page)
  await expect(settings.getByRole('switch', { name: 'Advanced display' })).toBeChecked()
  await settings.getByRole('switch', { name: 'Advanced display' }).uncheck()
  await settings.getByRole('button', { name: 'Close', exact: true }).click()
  settings = await openSettings(page)
  await expect(settings.getByRole('switch', { name: 'Advanced display' })).not.toBeChecked()
  await page.reload()
  await page.getByRole('button', { name: 'I understand', exact: true }).click()
  settings = await openSettings(page)
  await expect(settings.getByRole('switch', { name: 'Advanced display' })).toBeChecked()
})

test('production non-loopback defaults advanced off and remembers an explicit preference', async ({ page, baseURL }, testInfo) => {
  test.skip(!testInfo.project.name.includes('production'), 'Uses the production bundle under a non-loopback hostname.')
  await page.route('https://jst.example/**', async (route) => {
    const url = new URL(route.request().url())
    if (url.pathname === '/sw.js') return route.abort()
    const response = await page.request.get(`${baseURL}${url.pathname}${url.search}`)
    await route.fulfill({ response })
  })
  await page.goto('https://jst.example/privacy')
  await page.getByRole('button', { name: 'I understand', exact: true }).click()
  const settings = await openSettings(page)
  await expect(settings.getByRole('switch', { name: 'Advanced display' })).not.toBeChecked()
  await settings.getByRole('switch', { name: 'Advanced display' }).check()
  await settings.getByRole('button', { name: 'Close', exact: true }).click()
  await page.reload()
  const reopened = await openSettings(page)
  await expect(reopened.getByRole('switch', { name: 'Advanced display' })).toBeChecked()
})
