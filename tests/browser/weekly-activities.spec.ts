for (const timezoneId of ['America/Los_Angeles', 'Pacific/Kiritimati']) {
  test.describe(`calendar grouping in ${timezoneId}`, () => {
    test.use({ timezoneId })
    test('groups year-boundary Sunday/Saturday, includes gaps, and moves edited records between weeks', async ({ page }) => {
      test.setTimeout(120_000)
      const overview = page.getByRole('navigation', { name: 'Activity weeks', exact: true })
      const week = page.getByRole('region', { name: 'Selected activity week', exact: true })
      const records = week.getByRole('listitem')
      const detail = page.getByRole('region', { name: 'Activity details', exact: true })
      await addActivity(page, '2025-12-28', 'Sunday activity')
      await addActivity(page, '2026-01-03', 'Saturday activity')
      await addActivity(page, '2026-01-01', 'New year activity')
      await addActivity(page, '2025-12-29', 'Fourth activity, no weekly cap')
      await expect(records).toHaveCount(4)
      await expect(week.getByRole('heading', { name: 'Week: 2025-12-28 to 2026-01-03', exact: true })).toBeVisible()
      await expect(overview.getByRole('button', { name: 'Week 2025-12-28 to 2026-01-03, 4 activities', exact: true })).toHaveAttribute('aria-pressed', 'true')
      await expect(records.first()).toContainText('Saturday activity')
      await expect(records.last()).toContainText('Sunday activity')
      await addActivity(page, '2026-01-18', 'Latest week')
      await expect(overview).toContainText('4 weeks, 2 empty')
      await expect(overview.getByRole('button', { name: /^Week / })).toHaveCount(4)
      await expect(week.getByRole('heading', { name: 'Week: 2026-01-18 to 2026-01-24', exact: true })).toBeVisible()
      await page.reload()
      await expect(week.getByRole('heading', { name: 'Week: 2026-01-18 to 2026-01-24', exact: true })).toBeVisible()
      const gap = overview.getByRole('button', { name: 'Week 2026-01-04 to 2026-01-10, No activities recorded', exact: true })
      await gap.focus()
      await page.keyboard.press('Enter')
      await expect(gap).toHaveAttribute('aria-pressed', 'true')
      await expect(week).toContainText('No activities recorded for this week.')
      await expect(page.getByText('No activities yet.', { exact: false })).toHaveCount(0)
      await overview.getByRole('button', { name: 'Week 2025-12-28 to 2026-01-03, 4 activities', exact: true }).click()
      await week.getByRole('button', { name: /^Saturday activity,/ }).click()
      const recordId = (await detail.locator('p').filter({ hasText: /^Record ID:/ }).textContent())!.replace('Record ID: ', '')
      await detail.getByRole('button', { name: 'Edit activity', exact: true }).click()
      const form = page.getByRole('dialog', { name: 'Edit activity', exact: true })
      await form.getByLabel(/^Activity date/).fill('2026-01-04')
      await form.getByRole('button', { name: 'Save activity', exact: true }).click()
      await expect(form).toBeHidden()
      await expect(week.getByRole('heading', { name: 'Week: 2026-01-04 to 2026-01-10', exact: true })).toBeVisible()
      await expect(detail).toContainText(`Record ID: ${recordId}`)
      await expect(overview.getByRole('button', { name: 'Week 2025-12-28 to 2026-01-03, 3 activities', exact: true })).toBeVisible()
      await expect(overview).toContainText('4 weeks, 1 empty')
      await week.getByRole('button', { name: 'Previous week', exact: true }).click()
      await expect(records).toHaveCount(3)
      await expect(week).not.toContainText('Saturday activity')
      await expect(detail).toHaveCount(0)
      await week.getByRole('button', { name: 'Next week', exact: true }).click()
      await week.locator(`button[data-record-id="${recordId}"]`).click()
      await detail.getByRole('button', { name: 'Delete activity', exact: true }).click()
      const confirmation = page.getByRole('dialog', { name: 'Delete activity?', exact: true })
      await confirmation.getByRole('button', { name: 'Delete activity', exact: true }).click()
      await expect(confirmation).toBeHidden()
      await expect(week).toContainText('No activities recorded for this week.')
      await expect(gap).toHaveAttribute('aria-pressed', 'true')
      await expect(overview).toContainText('4 weeks, 2 empty')
      await page.reload()
      await expect(week.getByRole('heading', { name: 'Week: 2026-01-18 to 2026-01-24', exact: true })).toBeVisible()
      await gap.click()
      await expect(week).toContainText('No activities recorded for this week.')
    })
  })
}

test('browses a long history including gaps on mobile, jumps outside it, and navigates while read-only', async ({ page }) => {
  test.setTimeout(120_000)
  await page.setViewportSize({ width: 390, height: 844 })
  const overview = page.getByRole('navigation', { name: 'Activity weeks', exact: true })
  const week = page.getByRole('region', { name: 'Selected activity week', exact: true })
  await expect(overview).toHaveCount(0)
  await expect(week).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Previous week', exact: true })).toHaveCount(0)
  const section = page.getByRole('region', { name: 'Job-search activities', exact: true })
  await expect(section.getByText(/This log does not determine ESD/)).toBeHidden()
  await section.locator('summary').click()
  await expect(section.getByText(/This log does not determine ESD/)).toBeVisible()
  await section.locator('summary').click()
  const today = await page.evaluate(() => {
    const now = new Date()
    return `${String(now.getFullYear()).padStart(4, '0')}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`
  })
  await page.getByRole('button', { name: 'Add activity', exact: true }).click()
  let form = page.getByRole('dialog', { name: 'Add activity', exact: true })
  await expect(form.getByLabel(/^Activity date/)).toHaveValue(today)
  await form.getByRole('button', { name: 'Cancel', exact: true }).click()
  await addActivity(page, '2025-01-05', 'Oldest week')
  await addActivity(page, '2026-01-04', 'Newest week')
  const originalUrl = page.url()
  await expect(overview).toContainText('53 weeks, 51 empty')
  await expect(week.getByLabel(/^Jump to week containing/)).toBeHidden()
  await expect(overview).toContainText('Showing weeks 1-12 of 53')
  await expect(overview.getByRole('button', { name: /^Week / })).toHaveCount(12)
  await overview.getByRole('button', { name: 'Older weeks', exact: true }).click()
  await expect(overview).toContainText('Showing weeks 13-24 of 53')
  await overview.getByRole('button', { name: /^Week .*No activities recorded$/ }).first().click()
  await expect(week).toContainText('No activities recorded for this week.')
  const selectedHeading = await week.getByRole('heading', { level: 3 }).innerText()
  const hideEmpty = overview.getByRole('switch', { name: 'Hide empty weeks', exact: true })
  await expect(hideEmpty).not.toBeChecked()
  await hideEmpty.check()
  await expect(overview.getByRole('button', { name: /^Week / })).toHaveCount(2)
  await expect(overview.getByRole('button', { name: /No activities recorded$/ })).toHaveCount(0)
  await expect(overview.getByRole('button', { name: 'Older weeks', exact: true })).toHaveCount(0)
  await expect(overview).toContainText('The selected week has no activities and is hidden')
  await expect(week.getByRole('heading', { level: 3 })).toHaveText(selectedHeading)
  await overview.getByRole('button', { name: 'Week 2025-01-05 to 2025-01-11, 1 activity', exact: true }).click()
  await expect(week.getByRole('button', { name: /^Oldest week,/ })).toBeVisible()
  await expect(overview.getByText(/The selected week has no activities/)).toHaveCount(0)
  await hideEmpty.uncheck()
  await expect(overview).toContainText('Showing weeks 49-53 of 53')
  await expect(overview.getByRole('button', { name: /^Week .*No activities recorded$/ })).toHaveCount(4)
  await jumpToWeek(page, '2025-01-11')
  await expect(overview).toContainText('Showing weeks 49-53 of 53')
  await expect(overview.getByRole('button', { name: 'Older weeks', exact: true })).toBeDisabled()
  await expect(overview.getByRole('button', { name: 'Week 2025-01-05 to 2025-01-11, 1 activity', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await week.getByRole('button', { name: /^Oldest week,/ }).click()
  await expect(page.getByRole('region', { name: 'Activity details', exact: true })).toContainText('Oldest week')
  await week.getByRole('button', { name: 'Previous week', exact: true }).click()
  await expect(week).toContainText('outside the recorded activity range')
  await expect(week).toContainText('No activities recorded for this week.')
  await expect(page.getByRole('region', { name: 'Activity details', exact: true })).toHaveCount(0)
  await week.getByLabel(/^Jump to week containing/).fill('')
  await week.getByRole('button', { name: 'Go to week', exact: true }).click()
  await expect(week).toContainText('Choose a complete, real calendar date')
  await expect(week.getByRole('heading', { name: 'Week: 2024-12-29 to 2025-01-04', exact: true })).toBeVisible()
  await week.getByRole('button', { name: 'Current week', exact: true }).click()
  await expect(week.getByRole('button', { name: 'Current week', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Add activity', exact: true }).click()
  form = page.getByRole('dialog', { name: 'Add activity', exact: true })
  await expect(form.getByLabel(/^Activity date/)).toHaveValue(today)
  await form.getByRole('button', { name: 'Cancel', exact: true }).click()
  const currentHeading = await week.getByRole('heading', { level: 3 }).innerText()
  await jumpToWeek(page, today)
  await expect(week.getByRole('heading', { level: 3 })).toHaveText(currentHeading)
  await createClaim(page, 'Other weekly claim')
  await expect(overview).toHaveCount(0)
  await expect(week).toHaveCount(0)
  await page.goto(originalUrl)
  await expect(overview).toContainText('53 weeks, 51 empty')
  await page.addInitScript(() => {
    Object.defineProperty(navigator.storage, 'persisted', { configurable: true, value: async () => false })
  })
  await page.reload()
  await expect(page.getByRole('button', { name: 'Add activity', exact: true })).toBeDisabled()
  await jumpToWeek(page, '2025-01-05')
  await expect(week.getByRole('button', { name: /^Oldest week,/ })).toBeEnabled()
  await week.getByRole('button', { name: /^Oldest week,/ }).click()
  await expect(week.getByRole('button', { name: 'Edit activity', exact: true })).toBeDisabled()
  await expect(week.getByRole('button', { name: 'Delete activity', exact: true })).toBeDisabled()
  const overviewBox = await overview.boundingBox()
  const weekBox = await week.boundingBox()
  expect(overviewBox!.y + overviewBox!.height).toBeLessThanOrEqual(weekBox!.y)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('paginates only recorded weeks when empty weeks are hidden and updates after deletion', async ({ page }) => {
  test.setTimeout(180_000)
  const overview = page.getByRole('navigation', { name: 'Activity weeks', exact: true })
  const week = page.getByRole('region', { name: 'Selected activity week', exact: true })
  for (let index = 0; index < 13; index++) {
    const date = new Date(Date.UTC(2026, 0, 4 + index * 14)).toISOString().slice(0, 10)
    await addActivity(page, date, `Recorded week ${index + 1}`)
  }
  await overview.getByRole('switch', { name: 'Hide empty weeks', exact: true }).check()
  await expect(overview).toContainText('Showing weeks 1-12 of 13')
  await expect(overview.getByRole('button', { name: /^Week / })).toHaveCount(12)
  await expect(overview.getByRole('button', { name: /No activities recorded$/ })).toHaveCount(0)
  await overview.getByRole('button', { name: 'Older weeks', exact: true }).click()
  await expect(overview).toContainText('Showing weeks 13-13 of 13')
  await expect(overview.getByRole('button', { name: /^Week / })).toHaveCount(1)
  await overview.getByRole('button', { name: 'Week 2026-01-04 to 2026-01-10, 1 activity', exact: true }).click()
  await week.getByRole('button', { name: /^Recorded week 1,/ }).click()
  await week.getByRole('button', { name: 'Delete activity', exact: true }).click()
  const confirmation = page.getByRole('dialog', { name: 'Delete activity?', exact: true })
  await confirmation.getByRole('button', { name: 'Delete activity', exact: true }).click()
  await expect(confirmation).toBeHidden()
  await expect(overview.getByRole('button', { name: /^Week / })).toHaveCount(12)
  await expect(overview.getByRole('button', { name: 'Older weeks', exact: true })).toHaveCount(0)
  await expect(overview).toContainText('The selected week has no activities and is hidden')
  await expect(week).toContainText('No activities recorded for this week.')
})

test('supports the first and last calendar weeks and removes derived history after the last activity is deleted', async ({ page }) => {
  const overview = page.getByRole('navigation', { name: 'Activity weeks', exact: true })
  const week = page.getByRole('region', { name: 'Selected activity week', exact: true })
  await addActivity(page, '2026-01-01', 'Temporary activity')
  await jumpToWeek(page, '0001-01-01')
  await expect(week.getByRole('heading', { name: 'Week: 0000-12-31 to 0001-01-06', exact: true })).toBeVisible()
  await expect(week.getByRole('button', { name: 'Previous week', exact: true })).toBeDisabled()
  await expect(week.getByLabel(/^Jump to week containing/)).toHaveValue('0001-01-01')
  await week.getByRole('button', { name: 'Next week', exact: true }).click()
  await expect(week.getByRole('heading', { name: 'Week: 0001-01-07 to 0001-01-13', exact: true })).toBeVisible()
  await jumpToWeek(page, '9999-12-31')
  await expect(week.getByRole('heading', { name: 'Week: 9999-12-26 to 10000-01-01', exact: true })).toBeVisible()
  await expect(week.getByRole('button', { name: 'Next week', exact: true })).toBeDisabled()
  await addActivity(page, '9999-12-31', 'Final week')
  await jumpToWeek(page, '2026-01-01')
  await week.getByRole('button', { name: /^Temporary activity,/ }).click()
  await week.getByRole('button', { name: 'Delete activity', exact: true }).click()
  let confirmation = page.getByRole('dialog', { name: 'Delete activity?', exact: true })
  await confirmation.getByRole('button', { name: 'Delete activity', exact: true }).click()
  await expect(confirmation).toBeHidden()
  await addActivity(page, '0001-01-01', 'First week')
  expect(await overview.getByRole('button', { name: /^Week / }).count()).toBeLessThanOrEqual(12)
  await expect(overview.getByRole('button', { name: 'Week 0000-12-31 to 0001-01-06, 1 activity', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('region', { name: 'Activity details', exact: true }).getByRole('button', { name: 'Delete activity', exact: true }).click()
  confirmation = page.getByRole('dialog', { name: 'Delete activity?', exact: true })
  await confirmation.getByRole('button', { name: 'Delete activity', exact: true }).click()
  await expect(confirmation).toBeHidden()
  await expect(overview).toContainText('1 week, 0 empty')
  await expect(week).toContainText('No activities recorded for this week.')
  await overview.getByRole('button', { name: 'Week 9999-12-26 to 10000-01-01, 1 activity', exact: true }).click()
  await week.getByRole('button', { name: /^Final week,/ }).click()
  await week.getByRole('button', { name: 'Delete activity', exact: true }).click()
  await confirmation.getByRole('button', { name: 'Delete activity', exact: true }).click()
  await expect(confirmation).toBeHidden()
  await expect(overview).toHaveCount(0)
  await expect(week).toHaveCount(0)
  await expect(page.getByText('No activities yet.', { exact: false })).toBeVisible()
})
